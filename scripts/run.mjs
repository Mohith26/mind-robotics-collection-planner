// Fit the learning-curve model on all releases, plan the next two weeks of capture, backtest the forecasts,
// and check every plan against the simulator's ground truth. Writes data/bundle.js for the page.
import { readFileSync, writeFileSync } from 'node:fs';
import {
  fitModel, drawPosterior, pointParams, predictSlice, knobCurve, planExact, planGreedy, planEven,
  planByVolume, planWorstFirst, allocGain, allocUse, evalAlloc, backtest, failRate,
} from '../core/planner.mjs';

const plant = JSON.parse(readFileSync(new URL('../data/plant.json', import.meta.url)));
const truth = JSON.parse(readFileSync(new URL('../data/truth.json', import.meta.url)));
const DRAWS = 400, SEED = 11;

export function analyze(plant, budget = plant.budget) {
  const fit = fitModel(plant);
  const draws = drawPosterior(fit, DRAWS, SEED);
  const curves = plant.knobs.map((k) => knobCurve(k, draws, plant.nNow, plant.weights));
  const exact = planExact(plant.knobs, curves, budget);
  const greedy = planGreedy(plant.knobs, curves, budget);
  return { fit, draws, curves, exact, greedy };
}

const t0 = Date.now();
const { fit, draws, curves, exact, greedy } = analyze(plant);
const ms = Date.now() - t0;
const budget = plant.budget;
const plans = {
  planner: exact.alloc,
  greedy: greedy.alloc,
  even: planEven(plant.knobs, budget),
  volume: planByVolume(plant.knobs, budget, plant.weights),
  worst: planWorstFirst(plant.knobs, budget, curves),
};
const baseNow = curves.reduce((a, c) => a + c[0], 0);
const out = { model: {}, truth: {} };
for (const [name, alloc] of Object.entries(plans)) {
  out.model[name] = { gain: allocGain(curves, alloc), after: baseNow - allocGain(curves, alloc), use: allocUse(plant.knobs, alloc), alloc };
  const tNow = evalAlloc(plant.knobs, alloc.map(() => 0), truth.slices, plant.nNow, plant.weights).failsPerDay;
  const tAfter = evalAlloc(plant.knobs, alloc, truth.slices, plant.nNow, plant.weights).failsPerDay;
  out.truth[name] = { now: tNow, after: tAfter, gain: tNow - tAfter };
}
const bt = backtest(plant, 7, 600, 7);

// per-slice now / after under the plan, with intervals
const added = evalAlloc(plant.knobs, exact.alloc, pointParams(fit), plant.nNow, plant.weights).added;
const sliceRows = plant.slices.map((sl, s) => {
  const now = predictSlice(draws, s, plant.nNow[s]);
  const after = predictSlice(draws, s, plant.nNow[s] + added[s]);
  return { s, now, after, added: added[s], truthNow: failRate(truth.slices[s], plant.nNow[s]), truthAfter: failRate(truth.slices[s], plant.nNow[s] + added[s]) };
});

const bundle = {
  generated: 'scripts/run.mjs', draws: DRAWS, seed: SEED, fitMs: ms,
  scales: fit.scales, iters: fit.iters, nObs: fit.nObs, params: fit.idx.P,
  plans: out, baseNow, backtest: { cut: bt.cut, coverage: bt.coverage, mae: bt.mae, maeNaive: bt.maeNaive, maeModelSame: bt.maeModelSame, n: bt.n, rows: bt.rows },
  sliceRows,
};
writeFileSync(new URL('../data/bundle.js', import.meta.url),
  '// generated by scripts/run.mjs\nwindow.PLANT = ' + JSON.stringify(plant) + ';\nwindow.BUNDLE = ' + JSON.stringify(bundle) + ';\n');
console.log('fit ms', ms, 'scales', fit.scales, 'iters', fit.iters);
console.log('now (model) failed/day', baseNow.toFixed(1));
for (const k of Object.keys(plans)) console.log(k.padEnd(8), 'model after', out.model[k].after.toFixed(1), 'truth now', out.truth[k].now.toFixed(1), 'truth after', out.truth[k].after.toFixed(1), 'use', JSON.stringify(out.model[k].use));
console.log('backtest coverage', bt.coverage.toFixed(3), 'mae', bt.mae.toFixed(4), 'naive', bt.maeNaive.toFixed(4), 'modelSame', bt.maeModelSame.toFixed(4), 'n', bt.n);
console.log('alloc', exact.alloc.join(','));
